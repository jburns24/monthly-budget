"""Generate the API contract docs from the FastAPI OpenAPI schema.

Writes two files at the repo root, both GENERATED (do not hand-edit):

- ``docs/openapi.json`` -- the full OpenAPI schema, dev-only routes removed.
- ``docs/api-contract.md`` -- one row per operation: method, path, request and
  response schema, and the ``frontend/src/api/*.ts`` module(s) that call it.

Usage (from ``backend/``)::

    uv run python scripts/gen_api_contract.py           # regenerate
    uv run python scripts/gen_api_contract.py --check   # exit 1 if stale

``tests/test_api_contract.py`` runs the ``--check`` comparison in CI. No database
or network is touched: importing ``app.main`` only builds the app object.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

BACKEND_DIR = Path(__file__).resolve().parents[1]
REPO_ROOT = BACKEND_DIR.parent
OPENAPI_PATH = REPO_ROOT / "docs" / "openapi.json"
CONTRACT_PATH = REPO_ROOT / "docs" / "api-contract.md"
FRONTEND_API_DIR = REPO_ROOT / "frontend" / "src" / "api"

_METHODS = ("get", "post", "put", "patch", "delete")
_DEV_TAG = "dev"


def build_openapi() -> dict[str, Any]:
    """Return the app's OpenAPI schema without the dev-only (``tags=["dev"]``) operations."""
    sys.path.insert(0, str(BACKEND_DIR))
    from fastapi.openapi.utils import get_openapi  # noqa: PLC0415

    from app.main import app  # noqa: PLC0415 -- deferred so --help works without app deps

    # Build from the non-dev routes rather than filtering app.openapi(), so dev-only
    # schemas never reach components and the output is identical in every ENVIRONMENT.
    routes = [r for r in app.routes if _DEV_TAG not in getattr(r, "tags", [])]
    schema = get_openapi(
        title=app.title,
        version=app.version,
        openapi_version=app.openapi_version,
        description=app.description,
        routes=routes,
    )
    return schema


def _normalize(path: str) -> str:
    """Collapse every path parameter to ``{}`` so FastAPI and frontend paths compare."""
    return re.sub(r"\{[^}]*\}", "{}", path.rstrip("/"))


def frontend_calls() -> dict[str, set[str]]:
    """Map normalized ``/api/...`` paths to the frontend api modules that reference them.

    Static, best-effort scan of string/template literals; method is not inferred.
    Resolves ``const base = (x) => `...``` helpers so ``${base(id)}/...`` maps too.
    """
    found: dict[str, set[str]] = {}
    for ts in sorted(FRONTEND_API_DIR.glob("*.ts")):
        src = ts.read_text()
        for name, tmpl in re.findall(r"const (\w+) = \([^)]*\) =>\s*`([^`]*)`", src):
            # str.replace-style callables keep backslashes in the template literal.
            inline, quoted = tmpl, "`" + tmpl + "`"
            src = re.sub(r"\$\{" + name + r"\([^)]*\)\}", lambda _m: inline, src)
            src = re.sub(r"\b" + name + r"\([^)]*\)", lambda _m: quoted, src)
        for raw in re.findall(r"/api/[A-Za-z0-9_\-/${}.]*", src):
            raw = re.sub(r"\$\{[^}]*$", "", raw)  # dangling ${qs ? ... before a query string
            path = re.sub(r"\$\{[^}]*\}", "{}", raw)
            found.setdefault(_normalize(path), set()).add(f"api/{ts.stem}.ts")
    return found


def _schema_name(schema: dict[str, Any] | None) -> str:
    if not schema:
        return "—"
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if schema.get("type") == "array":
        return f"list[{_schema_name(schema.get('items'))}]"
    if "anyOf" in schema:
        return " \\| ".join(_schema_name(s) for s in schema["anyOf"])
    return str(schema.get("type", "object"))


def _request(op: dict[str, Any]) -> str:
    content = op.get("requestBody", {}).get("content", {})
    for ctype, body in content.items():
        name = _schema_name(body.get("schema"))
        return name if ctype == "application/json" else f"{name} ({ctype})"
    return "—"


def _response(op: dict[str, Any]) -> str:
    for code, resp in sorted(op.get("responses", {}).items()):
        if code.startswith("2"):
            schema = resp.get("content", {}).get("application/json", {}).get("schema")
            return f"{code} {_schema_name(schema)}" if schema else f"{code} —"
    return "—"


def frontend_orphans(schema: dict[str, Any], calls: dict[str, set[str]] | None = None) -> list[str]:
    """Frontend ``/api`` paths that no (non-dev) backend route serves."""
    calls = frontend_calls() if calls is None else calls
    backend_paths = {_normalize(p) for p in schema["paths"]}
    return sorted(p for p in calls if p not in backend_paths)


def render_contract(schema: dict[str, Any]) -> str:
    calls = frontend_calls()
    lines = [
        "# API contract",
        "",
        "<!-- GENERATED by backend/scripts/gen_api_contract.py from the FastAPI OpenAPI schema. Do not edit. -->",
        "",
        "Regenerate with `task be:api-contract` (or `uv run python scripts/gen_api_contract.py` from `backend/`).",
        "`tests/test_api_contract.py` fails CI when this file or `docs/openapi.json` is stale.",
        'Dev-only routes (`tags=["dev"]`, mounted only when `ENVIRONMENT` is development/test) are omitted.',
        "The frontend column is a static scan of `frontend/src/api/*.ts`; it matches paths, not methods.",
        "",
        "| Method | Path | Request | Response | Frontend |",
        "|---|---|---|---|---|",
    ]
    backend_paths: set[str] = set()
    for path in sorted(schema["paths"]):
        norm = _normalize(path)
        backend_paths.add(norm)
        modules = ", ".join(f"`{m}`" for m in sorted(calls.get(norm, set()))) or "—"
        for method in _METHODS:
            op = schema["paths"][path].get(method)
            if op:
                lines.append(f"| {method.upper()} | `{path}` | {_request(op)} | {_response(op)} | {modules} |")
    orphans = frontend_orphans(schema, calls)
    lines += ["", "## Frontend paths with no backend route", ""]
    if orphans:
        lines += [f"- `{p}` ({', '.join(sorted(calls[p]))})" for p in orphans]
    else:
        lines.append("None.")
    return "\n".join(lines) + "\n"


def render() -> dict[Path, str]:
    schema = build_openapi()
    return {
        OPENAPI_PATH: json.dumps(schema, indent=2, sort_keys=True) + "\n",
        CONTRACT_PATH: render_contract(schema),
    }


def stale_files() -> list[Path]:
    """Return the generated files whose on-disk content differs from a fresh render."""
    return [p for p, text in render().items() if not p.exists() or p.read_text() != text]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the generated files are stale")
    args = parser.parse_args()
    if args.check:
        stale = stale_files()
        for p in stale:
            print(f"stale: {p.relative_to(REPO_ROOT)} -- run `task be:api-contract`", file=sys.stderr)
        return 1 if stale else 0
    for path, text in render().items():
        path.write_text(text)
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
